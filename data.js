function hashN(s) { let h = 2166136261; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } return ((h >>> 0) % 2001) / 1000 - 1; }
const r1 = v => Math.round(v * 10) / 10;

function Q(name, age, role, bat, agg, tilt, bowl, pot, x) {
  x = x || {};
  const v = k => hashN(name + k);
  const conc = bat + (agg < 55 ? 2 : agg > 80 ? -2 : 0) + v('c') * 2;
  const tl = tilt + v('t') * 2;
  const sv = v('s');
  const p = {
    name, age, role, nat: x.nat, state: x.st || null, hand: x.h || 'R',
    bat: { tech: r1(bat + 1 + v('k') * 1.5), agg, vPace: r1(bat + tl), vSpin: r1(bat - tl), conc: r1(conc),
      off: r1(x.off != null ? x.off : bat + sv * 4), on: r1(x.on != null ? x.on : bat - sv * 4) },
    bowl: null, keep: x.keep || (role === 'WK' ? 80 : 0),
    field: r1(x.field || ((role === 'BOWL' ? 70 : 77) + v('f') * 5)), ground: 0,
    potRaw: pot || null, peak: x.peak || null, form: x.form || 0, prone: x.prone || 1, injury: null,
  };
  p.ground = r1(x.ground || p.field - 2 + v('g') * 4);
  if (bowl) {
    const [type, s] = bowl.split(' '); const sk = +s;
    const pace = ['RF', 'RFM', 'RM', 'LF', 'LFM'].includes(type);
    const mv = v('m');
    p.bowl = { type, skill: sk, acc: sk + (x.acc || 0), stam: x.stam || (pace ? 76 : 88) };
    if (pace) { p.bowl.swing = r1(x.swing || sk + mv * 6); p.bowl.seam = r1(x.seam || sk - mv * 6); }
    else { p.bowl.turn = r1(x.turn || sk + mv * 5); p.bowl.flight = r1(x.flight || sk - mv * 5); }
  }
  return p;
}

